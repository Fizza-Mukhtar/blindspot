def load_trajectory(path: Path) -> list[dict]:
    steps: list[dict] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            steps.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return steps


def render_index(files: list[Path], out: Path, *, max_bytes: int = 12_000_000) -> Path:
    """Inline every trajectory into one HTML file, newest-first, under a size cap."""
    runs: list[dict] = []
    budget = max_bytes
    for path in files:
        steps = load_trajectory(path)
        if not steps:
            continue
        payload = {"name": path.stem, "steps": steps}
        size = len(json.dumps(payload))
        if size > budget:
            # Keep the file openable rather than silently dropping runs: trim
            # this run's steps and say so.
            trimmed: list[dict] = list(steps[: max(10, len(steps) // 4)])
            payload["steps"] = trimmed
            trimmed.append(
                {
                    "step": 9999,
                    "event": "note",
                    "stage": "render",
                    "message": (
                        f"[trimmed by `blindspot trace` to stay under the "
                        f"{max_bytes // 1_000_000} MB page budget — the complete run is in "
                        f"{path.name}]"
                    ),
                }
            )
            size = len(json.dumps(payload))
        budget -= size
        runs.append(payload)
        if budget <= 0:
            break

    data = json.dumps(runs, ensure_ascii=False).replace("</script>", "<\\/script>")
    page = _TEMPLATE.replace("__DATA__", data).replace("__COUNT__", str(len(runs)))
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(page, encoding="utf-8")
    return out
