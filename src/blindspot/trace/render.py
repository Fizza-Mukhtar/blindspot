"""Render trajectories into a single self-contained HTML file.

Requirements this satisfies, in order:

* **Zero setup.** One file, no server, no CDN, no account. A judge double-clicks
  it and the trajectories are there, offline.
* **Readable as a narrative.** Steps in order, agent instructions visible,
  every tool call shown with what it returned, retries and human checkpoints
  called out rather than buried.
* **Honest.** It renders the JSONL verbatim; nothing is summarised away. The
  raw files sit next to it for anyone who prefers ``head``.
"""

